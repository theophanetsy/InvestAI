package dev.investai.shared.api;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Map;
import java.util.TreeMap;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;

/**
 * The Angular client versioned in the frontend is the one generated from {@code api/openapi.json}
 * by the build ({@code openapi-generator-maven-plugin}, ADR-0004).
 */
class AngularClientUpToDateTest {

  private static final Path GENERATED = Path.of("target", "angular-client");
  private static final Path VERSIONED = Path.of("..", "frontend", "src", "app", "api", "generated");

  @Test
  void versionedClientMatchesTheContract() {
    assertThat(GENERATED).as("client generated by the build").isDirectory();

    assertThat(typeScriptSources(VERSIONED))
        .as(
            "frontend/src/app/api/generated is not the client generated from api/openapi.json: run"
                + " `npm run api:update` from the repository root, never edit it by hand")
        .isEqualTo(typeScriptSources(GENERATED));
  }

  /** Relative path to content, line endings normalised. */
  private static Map<String, String> typeScriptSources(Path root) {
    Map<String, String> sources = new TreeMap<>();
    if (!Files.isDirectory(root)) {
      return sources;
    }
    try (Stream<Path> files = Files.walk(root)) {
      files
          .filter(file -> file.toString().endsWith(".ts"))
          .forEach(
              file ->
                  sources.put(
                      root.relativize(file).toString().replace('\\', '/'),
                      read(file).replace("\r\n", "\n")));
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
    return sources;
  }

  private static String read(Path file) {
    try {
      return Files.readString(file, StandardCharsets.UTF_8);
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
  }
}
