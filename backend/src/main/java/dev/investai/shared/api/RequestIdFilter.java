package dev.investai.shared.api;

import dev.investai.shared.logging.LogSanitizer;
import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;
import java.util.UUID;
import java.util.concurrent.TimeUnit;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.slf4j.MDC;
import org.springframework.core.Ordered;
import org.springframework.core.annotation.Order;
import org.springframework.stereotype.Component;
import org.springframework.web.filter.OncePerRequestFilter;
import org.springframework.web.servlet.HandlerMapping;

/**
 * Gives every HTTP request an identifier, exposes it in the {@code X-Request-Id} response header
 * and the logging MDC, and logs one summary line per request (ADR-0006).
 *
 * <p>The identifier is always generated by the server: a client cannot choose it, hence cannot
 * forge or collide with log content. Cross-service correlation will rely on W3C {@code traceparent}
 * (OpenTelemetry, Phase 3).
 */
@Component
@Order(Ordered.HIGHEST_PRECEDENCE)
public class RequestIdFilter extends OncePerRequestFilter {

  /** Response header carrying the request identifier. */
  public static final String HEADER = "X-Request-Id";

  /** Request attribute holding the identifier, for components outside the logging context. */
  public static final String REQUEST_ATTRIBUTE = RequestIdFilter.class.getName() + ".requestId";

  /** MDC key, rendered as a field of each JSON log line. */
  public static final String MDC_KEY = "requestId";

  private static final Logger LOG = LoggerFactory.getLogger(RequestIdFilter.class);
  private static final String UNMATCHED_ROUTE = "UNMATCHED";

  @Override
  protected void doFilterInternal(
      HttpServletRequest request, HttpServletResponse response, FilterChain chain)
      throws ServletException, IOException {
    String requestId = UUID.randomUUID().toString();
    request.setAttribute(REQUEST_ATTRIBUTE, requestId);
    response.setHeader(HEADER, requestId);
    MDC.put(MDC_KEY, requestId);
    long start = System.nanoTime();
    boolean failed = true;
    try {
      chain.doFilter(request, response);
      failed = false;
    } finally {
      long durationMs = TimeUnit.NANOSECONDS.toMillis(System.nanoTime() - start);
      String method = LogSanitizer.oneLine(request.getMethod());
      String route = LogSanitizer.oneLine(routeOf(request));
      // An exception escaping the chain only becomes a 500 after this filter has returned.
      int status = failed ? HttpServletResponse.SC_INTERNAL_SERVER_ERROR : response.getStatus();
      LOG.info("{} {} -> {} in {} ms", method, route, status, durationMs);
      MDC.remove(MDC_KEY);
    }
  }

  /** Route template selected by Spring MVC: never the raw URL, which may carry data. */
  private static String routeOf(HttpServletRequest request) {
    Object pattern = request.getAttribute(HandlerMapping.BEST_MATCHING_PATTERN_ATTRIBUTE);
    return pattern instanceof String route ? route : UNMATCHED_ROUTE;
  }
}
